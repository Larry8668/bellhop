import { describe, expect, it } from 'vitest';
import { allPhase2ScenarioIds, renderEvals, type EvalsRow } from '../../src/reporter/evals-reporter.js';

const FIXED_DATE = new Date('2026-11-06T12:00:00.000Z');

function row(overrides: Partial<EvalsRow> = {}): EvalsRow {
  return {
    scenario: 'S09',
    test: 'S09 timeout after success — verified, no duplicate',
    expected: 'verified, no duplicate',
    actual: 'pass',
    result: 'pass',
    ...overrides,
  };
}

describe('renderEvals (pure)', () => {
  it('includes the do-not-edit header and the run date from the caller', () => {
    const md = renderEvals([row()], [], FIXED_DATE);
    expect(md).toContain('Generated by `server/src/reporter/evals-reporter.ts` — do not edit by hand.');
    expect(md).toContain(`Run: ${FIXED_DATE.toISOString()}`);
  });

  it('renders one table row per test with the scenario/test/expected/actual/result columns', () => {
    const md = renderEvals([row()], [], FIXED_DATE);
    expect(md).toContain('| Scenario | Test | Expected | Actual | Result |');
    expect(md).toContain(
      '| S09 | S09 timeout after success — verified, no duplicate | verified, no duplicate | pass | pass |',
    );
  });

  it('sorts rows numerically by scenario id, not lexically (S02 before S10, H2 before H10)', () => {
    const rows = [
      row({ scenario: 'S10', test: 'S10 b' }),
      row({ scenario: 'H10', test: 'H10 c' }),
      row({ scenario: 'S02', test: 'S02 a' }),
      row({ scenario: 'H2', test: 'H2 d' }),
    ];
    const md = renderEvals(rows, [], FIXED_DATE);
    const order = [...md.matchAll(/\| (S\d{2}|H\d{1,2}) \|/g)].map((m) => m[1]);
    expect(order).toEqual(['S02', 'S10', 'H2', 'H10']);
  });

  it('computes totals from pass/fail/skip results', () => {
    const md = renderEvals(
      [row({ result: 'pass' }), row({ scenario: 'S10', result: 'fail' }), row({ scenario: 'S11', result: 'skip' })],
      [],
      FIXED_DATE,
    );
    expect(md).toContain('Totals: 1 passed / 1 failed / 1 skipped (3 total)');
  });

  it('lists every scenario id with no matching row under "not covered yet"', () => {
    const md = renderEvals([row({ scenario: 'S09' })], ['S09', 'S10', 'H1'], FIXED_DATE);
    expect(md).toContain('- S10: not covered yet');
    expect(md).toContain('- H1: not covered yet');
    expect(md).not.toContain('- S09: not covered yet');
  });

  it('says so when every scenario id has coverage', () => {
    const md = renderEvals([row({ scenario: 'S09' })], ['S09'], FIXED_DATE);
    expect(md).toContain('All listed scenarios have at least one test.');
  });

  it('escapes pipes and newlines inside cell text so the table stays well-formed', () => {
    const md = renderEvals(
      [row({ expected: 'a | b', actual: 'line1\nline2' })],
      [],
      FIXED_DATE,
    );
    expect(md).toContain('a \\| b');
    expect(md).toContain('line1 line2');
  });

  it('allPhase2ScenarioIds returns zero-padded S01..S16 and unpadded H1..H10', () => {
    const ids = allPhase2ScenarioIds();
    expect(ids[0]).toBe('S01');
    expect(ids[15]).toBe('S16');
    expect(ids).toHaveLength(26);
    expect(ids).toContain('H1');
    expect(ids).toContain('H10');
    expect(ids).not.toContain('H01');
  });
});
