import { writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Reporter, TestCase, TestModule } from 'vitest/node';

/** Every scenario-tagged test name starts with its id (`S09 timeout…`, `H2 approve…`). */
const SCENARIO_ID_PATTERN = /^(S\d{2}|H\d{1,2})\b/;

export type EvalsResult = 'pass' | 'fail' | 'skip';

export interface EvalsRow {
  scenario: string;
  test: string;
  expected: string;
  actual: string;
  result: EvalsResult;
}

/** Plan §16 order: core scenarios (`S`) before the hold/price matrix (`H`). */
const PREFIX_ORDER = ['S', 'H'] as const;

function parseScenarioId(id: string): { prefix: string; num: number } {
  const match = /^([A-Za-z]+)(\d+)$/.exec(id);
  if (match === null) return { prefix: id, num: 0 };
  return { prefix: match[1] ?? id, num: Number(match[2]) };
}

function prefixRank(prefix: string): number {
  const rank = PREFIX_ORDER.indexOf(prefix as (typeof PREFIX_ORDER)[number]);
  return rank === -1 ? PREFIX_ORDER.length : rank;
}

/** Numeric per-prefix order (`S01 < S02 < … < S16`, `H1 < H2 < … < H10`), not raw string order. */
function compareScenarioIds(a: string, b: string): number {
  const pa = parseScenarioId(a);
  const pb = parseScenarioId(b);
  if (pa.prefix !== pb.prefix) return prefixRank(pa.prefix) - prefixRank(pb.prefix);
  return pa.num - pb.num;
}

function firstLine(text: string): string {
  return text.split('\n')[0] ?? text;
}

function escapeCell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function expectedFromName(name: string, scenario: string): string {
  const rest = name.slice(scenario.length).trim();
  return rest.length > 0 ? rest : name;
}

/** `S01`…`S16`, `H1`…`H10` — the Phase 2 (core, no model) subset of plan §16. */
export function allPhase2ScenarioIds(): string[] {
  const s = Array.from({ length: 16 }, (_, i) => `S${String(i + 1).padStart(2, '0')}`);
  const h = Array.from({ length: 10 }, (_, i) => `H${i + 1}`);
  return [...s, ...h];
}

/**
 * Pure renderer, tested directly without spinning up Vitest's reporter
 * machinery. `date` comes from the caller (`new Date()` in `onTestRunEnd`,
 * never from this function) so tests can pass a fixed one.
 */
export function renderEvals(rows: readonly EvalsRow[], allScenarioIds: readonly string[], date: Date): string {
  const sorted = [...rows].sort((a, b) => {
    const byScenario = compareScenarioIds(a.scenario, b.scenario);
    return byScenario !== 0 ? byScenario : a.test.localeCompare(b.test);
  });

  const passed = sorted.filter((r) => r.result === 'pass').length;
  const failed = sorted.filter((r) => r.result === 'fail').length;
  const skipped = sorted.length - passed - failed;

  const covered = new Set(sorted.map((r) => r.scenario));
  const notCovered = allScenarioIds.filter((id) => !covered.has(id));

  const lines: string[] = [
    '# EVALS',
    '',
    'Generated by `server/src/reporter/evals-reporter.ts` — do not edit by hand.',
    `Run: ${date.toISOString()}`,
    '',
    `Totals: ${passed} passed / ${failed} failed / ${skipped} skipped (${sorted.length} total)`,
    '',
    '| Scenario | Test | Expected | Actual | Result |',
    '|---|---|---|---|---|',
  ];

  for (const row of sorted) {
    lines.push(
      `| ${escapeCell(row.scenario)} | ${escapeCell(row.test)} | ${escapeCell(row.expected)} | ${escapeCell(row.actual)} | ${row.result} |`,
    );
  }

  lines.push('', '## Not yet covered (plan §16, Phase 2 subset: S01–S16, H1–H10)', '');
  if (notCovered.length === 0) {
    lines.push('All listed scenarios have at least one test.');
  } else {
    for (const id of notCovered) lines.push(`- ${id}: not covered yet`);
  }
  lines.push('');

  return lines.join('\n');
}

function rowResult(testCase: TestCase): EvalsResult {
  const state = testCase.result().state;
  if (state === 'passed') return 'pass';
  if (state === 'failed') return 'fail';
  return 'skip'; // 'skipped' | 'pending' (shouldn't occur once the run has ended)
}

function defaultActual(testCase: TestCase, result: EvalsResult): string {
  if (result !== 'fail') return result === 'pass' ? 'pass' : 'skipped';
  const errors = testCase.result().errors;
  const message = errors?.[0]?.message;
  return message === undefined ? 'fail' : `fail: ${firstLine(message)}`;
}

function toRow(testCase: TestCase, scenario: string): EvalsRow {
  const meta = testCase.meta();
  const result = rowResult(testCase);
  return {
    scenario,
    test: testCase.name,
    expected: meta.expected ?? expectedFromName(testCase.name, scenario),
    actual: meta.actual ?? defaultActual(testCase, result),
    result,
  };
}

function collectRows(testModules: readonly TestModule[]): EvalsRow[] {
  const rows: EvalsRow[] = [];
  for (const testModule of testModules) {
    for (const testCase of testModule.children.allTests()) {
      const match = SCENARIO_ID_PATTERN.exec(testCase.name);
      if (match === null) continue;
      rows.push(toRow(testCase, match[1] ?? testCase.name));
    }
  }
  return rows;
}

export interface EvalsReporterOptions {
  /** Defaults to `../EVALS.md` relative to the current working directory (the `server/` package root). */
  outputPath?: string;
  /** All scenario ids expected to eventually have coverage; defaults to the Phase 2 subset (plan §16). */
  allScenarioIds?: readonly string[];
}

/**
 * Vitest reporter (plan §15/§16): on every `npm test`, regenerates
 * `EVALS.md` from every test whose name starts with a scenario id. Rendering
 * itself is a pure function (`renderEvals`) so it's tested without Vitest's
 * reporter machinery.
 */
export class EvalsReporter implements Reporter {
  private readonly outputPath: string;
  private readonly allScenarioIds: readonly string[];

  constructor(options: EvalsReporterOptions = {}) {
    this.outputPath = options.outputPath ?? path.join(process.cwd(), '..', 'EVALS.md');
    this.allScenarioIds = options.allScenarioIds ?? allPhase2ScenarioIds();
  }

  onTestRunEnd(testModules: readonly TestModule[]): void {
    const rows = collectRows(testModules);
    const markdown = renderEvals(rows, this.allScenarioIds, new Date());
    writeFileSync(this.outputPath, markdown);
  }
}
